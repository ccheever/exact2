/** A local repository with one commit and an origin remote (never fetched or pushed). */
export function seedRepository(paths, name, { repo, origin }) {
  const path = join(envDir(paths, name), "repos", repo);
  const env = serverEnv(paths, name);
  if (existsSync(join(path, ".git"))) return path;
  mkdirSync(path, { recursive: true });
  writeFileSync(join(path, "README.md"), `# ${repo}\n\nA fixture repository.\n`);
  const git = (args) => run("/usr/bin/git", args, { env: { ...env, GIT_AUTHOR_DATE: "2026-01-01T00:00:00Z", GIT_COMMITTER_DATE: "2026-01-01T00:00:00Z" }, cwd: path });
  git(["init", "--quiet", "-b", "main"]);
  git(["add", "README.md"]);
  git(["commit", "--quiet", "-m", "Start the notes"]);
  git(["remote", "add", "origin", origin]);
  return path;
}

/** The server's projects and threads (it answers 400 without the orchestration protocol header). */
async function shellSnapshot(conn) {
  const response = await fetch(`${conn.origin}/api/orchestration/shell`, { headers: { ...conn.auth, "x-t3-orchestration-protocol": "2" } });
  if (!response.ok) throw new Error(`orchestration shell: HTTP ${response.status}`);
  return response.json();
}

/** The provider instance the stand-in's turns run on (an `acpRegistry` instance of its agent id). */
export const STANDIN_INSTANCE = "acpRegistry_fixture-acp-standin";
export const standinInstance = () => ({ driver: "acpRegistry", displayName: AGENT.name, config: { agentId: AGENT.id } });

/**
 * Makes the ACP stand-in a provider of `name`'s server: installed into its home (with no sign-in
 * when it is not installed yet; an installed one keeps its mode and must be signed in) and added as
 * the `STANDIN_INSTANCE` provider instance through server.updateSettings, as Add provider does.
 * `bun ../acp-standin/install.mjs forget --home <t3home>` (server stopped) removes the instance.
 */
export async function addStandin(paths, name, conn, { timeoutMs = 20_000 } = {}) {
  const t3home = join(envDir(paths, name), "t3home");
  if (!standinStatus(t3home).installed) installStandin(t3home, { methods: "none" });
  else refreshStandin(t3home);
  await conn.request("server.updateSettings", { patch: {}, providerInstanceMutation: { operation: "upsert", instanceId: STANDIN_INSTANCE, instance: standinInstance() } });
  // The server registers the instance's adapter once its probe is done; a turn sent before then is refused.
  const started = Date.now();
  for (;;) {
    const provider = ((await conn.request("server.getConfig", {})).providers ?? []).find((entry) => entry.instanceId === STANDIN_INSTANCE);
    if (provider?.status === "ready") return;
    if (Date.now() - started > timeoutMs) throw new Error(`the ACP stand-in is not ready (${provider?.status ?? "not listed"}: ${provider?.message ?? "no message"}); sign it in or reinstall it with --mode none`);
    await Bun.sleep(250);
  }
}

/** A thread's turn is done when its shell row has a completion time for its latest run. */
export const turnCompleted = (thread) => !!thread?.latestRunId && !!thread?.latestRunCompletedAt && !thread?.activeRunId;
/**
 * An approval turn is seeded while its thread waits on the runtime request, or once a drive has answered
 * it and the turn completed; a server restart cancels the waiting turn, and the seed asks again.
 */
export const turnSeeded = (turn, thread) => (turn.approval ? !!thread?.pendingRuntimeRequest || (turnCompleted(thread) && thread.status === "completed") : turnCompleted(thread));

/**
 * One completed turn: a thread on the stand-in's instance (`existing`, else a new one) is sent
 * `prompt` (message.dispatch, as the composer's Send), waited for until its run completes, then
 * visited at that time, so it starts read, as a thread one has looked at; Mark unread is then the
 * only way to its "Completed" status. An `approval` turn runs in the runtime mode
 * "approval-required" and is waited for until the stand-in's permission request is pending.
 */
async function seedTurn(conn, projectId, { title, prompt, approval = false }, existing, { timeoutMs = 30_000 } = {}) {
  const threadId = existing ?? crypto.randomUUID();
  if (!existing) await conn.request("orchestration.dispatchCommand", {
    type: "thread.create", commandId: crypto.randomUUID(), createdBy: "user", creationSource: "web", threadId, projectId, title,
    modelSelection: { instanceId: STANDIN_INSTANCE, model: "default" }, runtimeMode: approval ? "approval-required" : "full-access", interactionMode: "default", branch: null, worktreePath: null,
  });
  await conn.request("orchestration.dispatchCommand", {
    type: "message.dispatch", commandId: crypto.randomUUID(), threadId, messageId: crypto.randomUUID(), text: prompt, attachments: [],
    createdBy: "user", creationSource: "web", deliveryIntent: "auto", dispatchMode: { type: "start_immediately" },
  });
  const started = Date.now();
  for (;;) {
    const thread = ((await shellSnapshot(conn)).threads ?? []).find((entry) => entry.id === threadId);
    if (approval && thread?.pendingRuntimeRequest) return threadId;
    if (turnCompleted(thread)) {
      await conn.request("orchestration.dispatchCommand", { type: "thread.visit", commandId: crypto.randomUUID(), threadId, visitedAt: thread.latestRunCompletedAt });
      return threadId;
    }
    if (thread?.status === "error" || Date.now() - started > timeoutMs) throw new Error(`${title}: no completed turn (status ${thread?.status ?? "missing"}${thread?.lastError ? `: ${thread.lastError}` : ""})`);
    await Bun.sleep(250);
  }
}

/**
 * The thread on the stand-in pull request's branch (no worktree; the branch need not exist): created
 * once, then waited for until the server has linked the pull request (thread.pull-request.sync).
 */
async function seedPullRequestThread(paths, name, conn, projectId, live, { timeoutMs = 30_000 } = {}) {
  installGhStandin(paths, name);
  const threadId = live.find((t) => t.title === PR_THREAD.title)?.id ?? crypto.randomUUID();
  if (!live.some((t) => t.id === threadId)) await conn.request("orchestration.dispatchCommand", {
    type: "thread.create", commandId: crypto.randomUUID(), createdBy: "user", creationSource: "web", threadId, projectId, title: PR_THREAD.title,
    modelSelection: { instanceId: "codex", model: "gpt-5.4" }, runtimeMode: "full-access", interactionMode: "default", branch: PR_THREAD.branch, worktreePath: null,
  });
  const started = Date.now();
  for (;;) {
    const thread = ((await shellSnapshot(conn)).threads ?? []).find((entry) => entry.id === threadId);
    if (thread?.branchPullRequest) return [`${PR_THREAD.title} (#${thread.branchPullRequest.number ?? "?"})`];
    if (Date.now() - started > timeoutMs) throw new Error(`${PR_THREAD.title}: no linked pull request after ${timeoutMs / 1000} s (see ${join(envDir(paths, name), "gh-calls.log")})`);
    await Bun.sleep(250);
  }
}

/** Projects and threads for `name`, through the running server's API. Idempotent by title. */
export async function seed(paths, name, seeds = SEEDS[name] ?? [], { turns = false, limits = false, pullRequest = false } = {}) {
  const running = recorded(paths, name);
  if (!running) throw new Error(`${name}: no fixture server running`);
  const conn = await connect(`http://127.0.0.1:${running.port}`, pairingToken(paths, name, "Fixture seed"));
  try {
    const out = [];
    if (limits) out.push({ usageHub: `http://127.0.0.1:${(await startHub(paths)).port}`, accounts: await addHub(conn, hubPort()) });
    // An installed stand-in older than agent.mjs is rewritten, and probed again so its skill is listed.
    if (turns && standinStatus(join(envDir(paths, name), "t3home")).installed && refreshStandin(join(envDir(paths, name), "t3home")))
      await conn.request("server.refreshProviders", { instanceId: STANDIN_INSTANCE }).catch(() => {});
    for (const entry of seeds) {
      const workspaceRoot = seedRepository(paths, name, entry);
      const projectId = await ensureProject(conn, workspaceRoot, { title: entry.repo, ...(entry.scripts ? { scripts: entry.scripts } : {}) });
      const shell = await shellSnapshot(conn);
      const live = (shell.threads ?? []).filter((t) => t.projectId === projectId && !t.archivedAt && !t.deletedAt);
      const have = new Set(live.map((t) => t.title));
      for (const title of entry.threads) {
        if (have.has(title)) continue;
        await conn.request("orchestration.dispatchCommand", {
          type: "thread.create", commandId: crypto.randomUUID(), createdBy: "user", creationSource: "web", threadId: crypto.randomUUID(), projectId, title,
          modelSelection: { instanceId: "codex", model: "gpt-5.4" }, runtimeMode: "full-access", interactionMode: "default", branch: null, worktreePath: null,
        });
      }
      // A turn thread is done once it holds a completed turn; one an interrupted seed left without it gets its turn now.
      const turnThreads = turns ? entry.turns ?? [] : [], pending = turnThreads.filter((turn) => !live.some((t) => t.title === turn.title && turnSeeded(turn, t)));
      if (pending.length) await addStandin(paths, name, conn);
      for (const turn of pending) await seedTurn(conn, projectId, turn, live.find((t) => t.title === turn.title)?.id);
      const prThread = pullRequest && entry.repo === PR_THREAD.repo ? await seedPullRequestThread(paths, name, conn, projectId, live) : [];
      out.push({ project: entry.repo, projectId, threads: [...entry.threads, ...turnThreads.map((turn) => turn.title), ...prThread] });
    }
    return out;
  } finally { conn.close(); }
}

/** Projects and live threads of a running environment, with their ids (a drive's targets are `thread-fleet:<environment>:<thread>`). */
export async function shellOf(paths, name) {
  const running = recorded(paths, name);
  if (!running) throw new Error(`${name}: no fixture server running`);
  const conn = await connect(`http://127.0.0.1:${running.port}`, pairingToken(paths, name, "Fixture status"));
  try {
    const shell = await shellSnapshot(conn);
    const projects = (shell.projects ?? []).filter((p) => !p.deletedAt);
    return projects.map((p) => ({ project: p.title, projectId: p.id, threads: (shell.threads ?? []).filter((t) => t.projectId === p.id && !t.archivedAt && !t.deletedAt).map((t) => ({ title: t.title, id: t.id })) }));
  } finally { conn.close(); }
}

