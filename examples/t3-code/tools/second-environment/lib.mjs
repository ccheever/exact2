// Extra T3 environments for drives of the clone: lane T3 servers (the official runtime the app
// stages), each on its own isolated homes under target/, seeded with projects and threads through
// the server's own API, and paired into the app by a drive. README.md has the recipe.
//
// A lane server sees none of this shell's homes, tokens or providers: its environment is built
// from nothing, every provider binary is pinned to a missing path, and its HTTP(S) goes to a proxy
// on a closed loopback port, so it reaches no provider, no registry and no GitHub. (A sandbox
// profile cannot do this: the server runs the setuid /bin/ps, which a sandboxed process may not.)
import { spawn, spawnSync } from "node:child_process";
import { chmodSync, existsSync, mkdirSync, openSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { connect as netConnect } from "node:net";
import { join, resolve } from "node:path";
import { connect, ensureProject } from "../github-lane/lib.mjs";

export const checkout = resolve(import.meta.dir, "../../../..");
export const example = join(checkout, "examples/t3-code");

/** The environments this fixture knows, their default ports, labels and seeds. */
export const ENVIRONMENTS = {
  second: { port: 16510, label: "Lane Second" },
  third: { port: 16511, label: "Lane Third" },
};
/** The port "This machine" (the app's embedded server) gets in a drive with `--local`. */
export const LOCAL_PORT = 16500;

/**
 * The ports a fixture may use: 16500-16599 unless `T3_FIXTURE_PORTS` (`lo-hi`) names another lane's
 * range. 3773 (a real T3 Code's) is never allowed.
 */
export function portRange(env = process.env) {
  const match = /^(\d+)-(\d+)$/.exec(env.T3_FIXTURE_PORTS ?? "");
  return match ? [Number(match[1]), Number(match[2])] : [16500, 16599];
}
export function checkPort(port, env = process.env) {
  const [lo, hi] = portRange(env);
  if (!Number.isInteger(port) || port < lo || port > hi || port === 3773) throw new Error(`fixture ports are ${lo}-${hi}, not ${port}`);
  return port;
}

/** Everything a fixture writes lives under `T3_FIXTURE_ROOT` (default `<checkout>/target/t3-fixtures`). */
export function fixturePaths(env = process.env) {
  const root = resolve(env.T3_FIXTURE_ROOT || join(checkout, "target/t3-fixtures"));
  return { root, runtime: join(root, "runtime"), envs: join(root, "envs"), local: join(root, "local"), drives: join(root, "drives") };
}
export const envDir = (paths, name) => join(paths.envs, name);

/** Provider settings that keep every built-in provider off a real binary (the lane rule). */
export const PINNED_PROVIDERS = Object.fromEntries(
  ["codex", "claudeAgent", "cursor", "grok", "pi", "opencode"].map((id) => [id, { binaryPath: `/nonexistent/t3-fixture/${id}` }]),
);

/**
 * `<t3 home>/userdata/settings.json` with the providers pinned; keys already there are kept, so a
 * provider instance a drive added (the ACP stand-in) survives a restart.
 */
export function seedSettings(t3home) {
  const file = join(t3home, "userdata/settings.json");
  mkdirSync(join(t3home, "userdata"), { recursive: true });
  const current = existsSync(file) ? JSON.parse(readFileSync(file, "utf8")) : {};
  const providers = { ...(current.providers ?? {}) };
  for (const [id, pin] of Object.entries(PINNED_PROVIDERS)) providers[id] = { ...(providers[id] ?? {}), ...pin };
  writeFileSync(file, `${JSON.stringify({ ...current, providers }, null, 2)}\n`);
  return file;
}

/**
 * The server asks `scutil --get ComputerName` for its environment label (reference
 * apps/server/src/environment/ServerEnvironmentLabel.ts resolveFriendlyHostLabel); this shim, first
 * on the lane PATH, answers with the lane's label so two environments on one Mac read apart.
 */
export const scutilShim = (label) => `#!/bin/sh
# Generated by examples/t3-code/tools/second-environment: the lane's environment label.
if [ "$1" = "--get" ] && [ "$2" = "ComputerName" ]; then printf '%s\\n' '${label.replaceAll("'", "")}'; exit 0; fi
exec /usr/sbin/scutil "$@"
`;

/**
 * The closed loopback port every lane server's HTTP(S) proxy points at (`T3_FIXTURE_OFFLINE_PORT`,
 * default 16599). Node's fetch honours it under NODE_USE_ENV_PROXY=1, Git and curl by the
 * variables themselves; loopback stays direct.
 */
export const offlinePort = (env = process.env) => checkPort(Number(env.T3_FIXTURE_OFFLINE_PORT ?? 16599), env);
export function offlineEnv(env = process.env) {
  const proxy = `http://127.0.0.1:${offlinePort(env)}`;
  return { NODE_USE_ENV_PROXY: "1", HTTPS_PROXY: proxy, HTTP_PROXY: proxy, https_proxy: proxy, http_proxy: proxy, ALL_PROXY: proxy, NO_PROXY: "127.0.0.1,localhost", no_proxy: "127.0.0.1,localhost" };
}
/** Refuses to start when something listens on the offline port: the proxy must refuse every connection. */
export async function assertOfflinePortClosed(env = process.env) {
  const port = offlinePort(env);
  const open = await new Promise((done) => {
    const socket = netConnect({ host: "127.0.0.1", port }, () => { socket.destroy(); done(true); });
    socket.on("error", () => done(false));
  });
  if (open) throw new Error(`something listens on ${port}, the offline proxy port; stop it or set T3_FIXTURE_OFFLINE_PORT`);
}

/** Writes an environment's homes, shims and settings. Idempotent. */
export function setupEnvironment(paths, name, { label = ENVIRONMENTS[name]?.label ?? `Lane ${name}` } = {}) {
  const dir = envDir(paths, name);
  for (const sub of ["t3home", "home", "bin", "codex", "claude", "xdg/config", "xdg/data", "xdg/cache", "xdg/state", "tmp", "repos"]) mkdirSync(join(dir, sub), { recursive: true });
  writeFileSync(join(dir, "bin/scutil"), scutilShim(label));
  chmodSync(join(dir, "bin/scutil"), 0o755);
  // The server rebuilds PATH from `zsh -ilc`; the profile keeps the shims first there too.
  writeFileSync(join(dir, "home/.zprofile"), `# Generated by examples/t3-code/tools/second-environment.\nexport PATH="${join(dir, "bin")}:$PATH"\n`);
  writeFileSync(join(dir, "home/.gitconfig"), `# Generated by examples/t3-code/tools/second-environment.\n[user]\n\tname = T3 fixture\n\temail = fixture@t3-fixture.invalid\n[init]\n\tdefaultBranch = main\n[credential]\n\thelper =\n`);
  seedSettings(join(dir, "t3home"));
  return dir;
}

/** The environment of a lane server, built from nothing: none of this shell's tokens, config or home reach it. */
export function serverEnv(paths, name, base = process.env) {
  const dir = envDir(paths, name);
  return {
    PATH: [join(dir, "bin"), "/usr/bin", "/bin", "/usr/sbin", "/sbin"].join(":"),
    HOME: join(dir, "home"), SHELL: "/bin/zsh", USER: base.USER ?? "", LOGNAME: base.LOGNAME ?? base.USER ?? "",
    LANG: base.LANG ?? "en_US.UTF-8", TMPDIR: join(dir, "tmp"),
    CODEX_HOME: join(dir, "codex"), CLAUDE_CONFIG_DIR: join(dir, "claude"),
    XDG_CONFIG_HOME: join(dir, "xdg/config"), XDG_DATA_HOME: join(dir, "xdg/data"), XDG_CACHE_HOME: join(dir, "xdg/cache"), XDG_STATE_HOME: join(dir, "xdg/state"),
    T3CODE_HOME: join(dir, "t3home"), T3CODE_TELEMETRY_ENABLED: "false", ...offlineEnv(base),
    GIT_CONFIG_NOSYSTEM: "1", GIT_TERMINAL_PROMPT: "0", GH_CONFIG_DIR: join(dir, "xdg/config/gh"), GH_PROMPT_DISABLED: "1",
  };
}

/** The staged release (`bun examples/t3-code/stage-runtime.mjs`), unpacked once under the fixture root. */
export function serverExecutable(paths) {
  if (process.env.T3_FIXTURE_SERVER) return process.env.T3_FIXTURE_SERVER;
  const pin = JSON.parse(readFileSync(join(example, "server-runtime/runtime-pin.json"), "utf8"));
  const tree = join(paths.runtime, pin.version), t3 = join(tree, "t3");
  if (!existsSync(t3)) {
    const archive = join(example, "server-runtime", pin.asset);
    if (!existsSync(archive)) throw new Error("no staged server: run `bun examples/t3-code/stage-runtime.mjs` first (or set T3_FIXTURE_SERVER)");
    mkdirSync(tree, { recursive: true });
    run("/usr/bin/tar", ["-xzf", archive, "-C", tree, "--strip-components=1"]);
  }
  return t3;
}

export function run(command, args, { env, cwd, input, allowFail = false } = {}) {
  const result = spawnSync(command, args, { env, cwd, input, encoding: "utf8", maxBuffer: 64 << 20 });
  if (result.error) throw result.error;
  const out = { status: result.status ?? 1, stdout: result.stdout ?? "", stderr: result.stderr ?? "" };
  if (out.status !== 0 && !allowFail) throw new Error(`${command.split("/").at(-1)} ${args.join(" ").slice(0, 200)}: exit ${out.status}: ${out.stderr.trim().slice(0, 600)}`);
  return out;
}

const pidFile = (paths, name) => join(envDir(paths, name), "server.pid");
const alive = (pid) => { try { process.kill(pid, 0); return true; } catch { return false; } };
/** The server this fixture started for `name`, while it runs: { pid, port }. */
export function recorded(paths, name) {
  if (!existsSync(pidFile(paths, name))) return null;
  const entry = JSON.parse(readFileSync(pidFile(paths, name), "utf8"));
  return alive(entry.pid) ? entry : null;
}

export async function waitReady(port, ms = 60_000) {
  const started = Date.now();
  while (Date.now() - started < ms) {
    try {
      const response = await fetch(`http://127.0.0.1:${port}/.well-known/t3/environment`, { signal: AbortSignal.timeout(1000) });
      if (response.ok) return await response.json();
    } catch {}
    await Bun.sleep(200);
  }
  throw new Error(`no server answered on ${port} within ${ms / 1000} s`);
}

/** Starts the lane server for `name` (offline, detached); returns { pid, port, environmentId, label }. */
export async function startServer(paths, name, { port = ENVIRONMENTS[name]?.port, label } = {}) {
  checkPort(port);
  const running = recorded(paths, name);
  if (running) return running;
  await assertOfflinePortClosed();
  const dir = setupEnvironment(paths, name, label ? { label } : {});
  const log = openSync(join(dir, "server.log"), "a");
  const t3 = serverExecutable(paths);
  const child = spawn(t3, ["serve", "--base-dir", join(dir, "t3home"), "--port", String(port), "--host", "127.0.0.1", join(dir, "repos")],
    { env: serverEnv(paths, name), cwd: join(dir, "repos"), stdio: ["ignore", log, log], detached: true });
  child.unref();
  writeFileSync(pidFile(paths, name), JSON.stringify({ pid: child.pid, port, startedAt: new Date().toISOString() }));
  try {
    const environment = await waitReady(port);
    const entry = { pid: child.pid, port, startedAt: new Date().toISOString(), environmentId: environment.environmentId, label: environment.label };
    writeFileSync(pidFile(paths, name), JSON.stringify(entry));
    // Kept after a stop: `forget` needs the origin and id a normal launch saved its token under.
    writeFileSync(join(dir, "environment.json"), JSON.stringify({ origin: `http://127.0.0.1:${port}`, environmentId: entry.environmentId, label: entry.label }));
    return entry;
  } catch (error) {
    stopServer(paths, name);
    throw new Error(`${error.message} (see ${join(dir, "server.log")})`);
  }
}

/** Stops the server this fixture recorded for `name` (its pid only) and waits until its port is free. */
export async function stopServer(paths, name) {
  const running = recorded(paths, name);
  rmSync(pidFile(paths, name), { force: true });
  if (!running) return null;
  process.kill(running.pid, "SIGTERM");
  for (let i = 0; i < 100 && alive(running.pid); i++) await Bun.sleep(100);
  if (alive(running.pid)) process.kill(running.pid, "SIGKILL");
  return running;
}

/** A single-use pairing token for a running environment (never printed). */
export function pairingToken(paths, name, label = "Fixture drive") {
  const dir = envDir(paths, name);
  const text = run(serverExecutable(paths), ["pair", "--base-dir", join(dir, "t3home"), "--ttl", "15m", "--label", label], { env: serverEnv(paths, name), cwd: join(dir, "repos") }).stdout;
  const token = /Token: (\S+)/.exec(text)?.[1];
  if (!token) throw new Error("t3 pair printed no token");
  return token;
}
export function pairingUrl(paths, name, label) {
  const running = recorded(paths, name);
  if (!running) throw new Error(`${name}: no fixture server running (bun env.mjs start ${name})`);
  return `http://127.0.0.1:${running.port}/pair#token=${pairingToken(paths, name, label)}`;
}

/**
 * The seeded content: "shared-notes" (one Git origin in every environment, so the clone groups it
 * as one logical project across machines) and, in `second` only, "background-only". Threads are
 * created with `thread.create` and never get a turn, so none has a completed run.
 */
export const SEEDS = {
  second: [
    { repo: "shared-notes", origin: "https://github.com/t3-fixture/shared-notes.git", threads: ["Shared notes on second"] },
    { repo: "background-only", origin: "https://github.com/t3-fixture/background-only.git", threads: ["Background thread (no run)", "Background follow-up"] },
  ],
  third: [
    { repo: "shared-notes", origin: "https://github.com/t3-fixture/shared-notes.git", threads: ["Shared notes on third"] },
  ],
};

/** A local repository with one commit and an origin remote (never fetched or pushed). */
export function seedRepository(paths, name, { repo, origin }) {
  const path = join(envDir(paths, name), "repos", repo);
  const env = serverEnv(paths, name);
  if (existsSync(join(path, ".git"))) return path;
  mkdirSync(path, { recursive: true });
  writeFileSync(join(path, "README.md"), `# ${repo}\n\nA fixture repository.\n`);
  const git = (args) => run("/usr/bin/git", args, { env: { ...env, GIT_AUTHOR_DATE: "2026-01-01T00:00:00Z", GIT_COMMITTER_DATE: "2026-01-01T00:00:00Z" }, cwd: path });
  git(["init", "--quiet", "-b", "main"]);
  git(["add", "README.md"]);
  git(["commit", "--quiet", "-m", "Start the notes"]);
  git(["remote", "add", "origin", origin]);
  return path;
}

/** The server's projects and threads (it answers 400 without the orchestration protocol header). */
async function shellSnapshot(conn) {
  const response = await fetch(`${conn.origin}/api/orchestration/shell`, { headers: { ...conn.auth, "x-t3-orchestration-protocol": "2" } });
  if (!response.ok) throw new Error(`orchestration shell: HTTP ${response.status}`);
  return response.json();
}

/** Projects and threads for `name`, through the running server's API. Idempotent by title. */
export async function seed(paths, name, seeds = SEEDS[name] ?? []) {
  const running = recorded(paths, name);
  if (!running) throw new Error(`${name}: no fixture server running`);
  const conn = await connect(`http://127.0.0.1:${running.port}`, pairingToken(paths, name, "Fixture seed"));
  try {
    const out = [];
    for (const entry of seeds) {
      const workspaceRoot = seedRepository(paths, name, entry);
      const projectId = await ensureProject(conn, workspaceRoot, { title: entry.repo });
      const shell = await shellSnapshot(conn);
      const have = new Set((shell.threads ?? []).filter((t) => t.projectId === projectId && !t.archivedAt && !t.deletedAt).map((t) => t.title));
      for (const title of entry.threads) {
        if (have.has(title)) continue;
        await conn.request("orchestration.dispatchCommand", {
          type: "thread.create", commandId: crypto.randomUUID(), createdBy: "user", creationSource: "web", threadId: crypto.randomUUID(), projectId, title,
          modelSelection: { instanceId: "codex", model: "gpt-5.4" }, runtimeMode: "full-access", interactionMode: "default", branch: null, worktreePath: null,
        });
      }
      out.push({ project: entry.repo, projectId, threads: entry.threads });
    }
    return out;
  } finally { conn.close(); }
}

/** Projects and live threads of a running environment, with their ids (a drive's targets are `thread-fleet:<environment>:<thread>`). */
export async function shellOf(paths, name) {
  const running = recorded(paths, name);
  if (!running) throw new Error(`${name}: no fixture server running`);
  const conn = await connect(`http://127.0.0.1:${running.port}`, pairingToken(paths, name, "Fixture status"));
  try {
    const shell = await shellSnapshot(conn);
    const projects = (shell.projects ?? []).filter((p) => !p.deletedAt);
    return projects.map((p) => ({ project: p.title, projectId: p.id, threads: (shell.threads ?? []).filter((t) => t.projectId === p.id && !t.archivedAt && !t.deletedAt).map((t) => ({ title: t.title, id: t.id })) }));
  } finally { conn.close(); }
}

/** The app's Keychain service for access tokens (modules/apple/T3Credentials.swift). */
export const KEYCHAIN_SERVICE = "com.exact.t3code.macos.access-token";
/**
 * Removes the access token a normal (non-agent) launch saved for a fixture environment: only the
 * account `<origin>\n<environmentId>` of that fixture's loopback origin. Returns whether one was there.
 */
export function forgetKeychain(origin, environmentId) {
  if (!/^http:\/\/127\.0\.0\.1:\d+$/.test(origin)) throw new Error(`not a fixture origin: ${origin}`);
  checkPort(Number(origin.split(":").at(-1)));
  const result = run("/usr/bin/security", ["delete-generic-password", "-s", KEYCHAIN_SERVICE, "-a", `${origin}\n${environmentId}`], { allowFail: true });
  if (result.status !== 0 && result.status !== 44) throw new Error(`security: exit ${result.status}: ${result.stderr.trim()}`);
  return result.status === 0;
}

/**
 * How long a drive waits for the welcome wizard before its first op (real ms). At its first start on a
 * home the app unpacks the pinned runtime into `<t3 home>/runtime/versions/<version>` (T3LocalRuntime.swift)
 * before "This machine" answers, which took longer than 5 s; with the runtime there 5 s is enough.
 */
export function welcomeWait(t3home) {
  const { version } = JSON.parse(readFileSync(join(example, "server-runtime/runtime-pin.json"), "utf8"));
  return existsSync(join(t3home, "runtime/versions", version)) ? 5000 : 20000;
}

/** "This machine"'s home for a drive with `--local`: providers pinned as in a lane environment. */
export function localHome(paths) {
  const t3home = join(paths.local, "t3home");
  seedSettings(t3home);
  return t3home;
}
