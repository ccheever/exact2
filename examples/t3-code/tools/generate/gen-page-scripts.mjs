// src/browser/page-scripts.ts: the scripts data code runs in a Browser tab's frame through `@exact/browser-automation`
// (Annotate's overlay, assets/browser-annotate.js, and its stylesheet, assets/browser-annotate.css; Playwright's
// injected script, assets/vendor/playwright), as string constants, since data code reads no bundled asset. Their
// sources stay the committed assets (generate.mjs `inputs`).
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const here = dirname(fileURLToPath(import.meta.url));
export const SOURCES = { ANNOTATE_OVERLAY: '../../assets/browser-annotate.js', ANNOTATE_STYLES: '../../assets/browser-annotate.css', PLAYWRIGHT_INJECTED: '../../assets/vendor/playwright/injected-script.js' };
export async function generate() {
  const lines = ['// Generated by tools/generate/gen-page-scripts.mjs from the assets it names. Never edited.'];
  for (const [name, path] of Object.entries(SOURCES)) lines.push(`export const ${name}: string = ${JSON.stringify(readFileSync(join(here, path), 'utf8'))};`);
  return [{ file: join(here, '../../src/browser/page-scripts.ts'), text: `${lines.join('\n')}\n` }];
}
