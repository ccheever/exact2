// shell-morph.contract: MorphIcon (MIT reference, see LICENSE-T3: apps/web/src/components/MorphIcon.tsx
// over morphicons 1.7.1, upstream f2cc80a7a4) as Contract, from morphicons' own plan for each icon pair
// (morphicons@1.7.1, MIT, and lucide@0.564.0's geometry, ISC, pinned in package.json). generate.mjs writes
// the file; MORPHS names the pairs.

import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildPlan, resampleIcon } from 'morphicons';

const here = dirname(fileURLToPath(import.meta.url));
const example = join(here, '..', '..');
const modules = join(here, 'node_modules');
const version = (name) => JSON.parse(readFileSync(join(modules, name, 'package.json'), 'utf8')).version;
const lucide = async (name) => (await import(join(modules, 'lucide/dist/esm/lucide/src/icons', `${name}.js`))).default;

/** The pairs the clone morphs: component, from-icon, to-icon. */
const MORPHS = [
  ['MorphCopyCheck', 'copy', 'check'],
  ['MorphMaximize', 'maximize-2', 'minimize-2'],
  ['MorphLock', 'lock-open', 'lock'],
  ['MorphQueueSteer', 'corner-up-right', 'list-plus'],
];
/** MorphIcon's "snappy" spring: stiffness, damping, mass. */
const SPRING = '-exact-spring(420, 30, 1)';

const round = n => { const r = Math.round(n * 100) / 100; return String(Object.is(r, -0) ? 0 : r); };
const percent = n => `${round((n / 24) * 100)}%`;
const polyline = (points, closed) => {
  let d = '';
  for (let at = 0; at < points.length; at += 2) d += `${at ? 'L' : 'M'}${round(points[at])} ${round(points[at + 1])}`;
  return closed ? `${d}Z` : d;
};

/** One subpath pair: a box at the source's centroid that drifts by the centroids' difference and turns
 *  by θ, holding a path whose `d` moves from the source polyline to the target's, unturned (σ·bT + c_A). */
function pair(item) {
  const sigma = Math.exp(item.lnSigma);
  const target = Array.from(item.bT, (v, at) => sigma * v + item.ca[at % 2]);
  const box = `\`\${size / 16}rem\``;
  return [
    `      box position="absolute" left=0 top=0 width=${box} height=${box} transform-origin="${percent(item.ca[0])} ${percent(item.ca[1])}" translate=(on ? "${percent(item.cb[0] - item.ca[0])} ${percent(item.cb[1] - item.ca[1])}" : "0% 0%") rotate=(on ? "${round((item.theta * 180) / Math.PI)}deg" : "0deg") transition=(still ? "none" : "translate ${SPRING}, rotate ${SPRING}")`,
    `        svg width=${box} height=${box} viewBox="0 0 24 24" overflow="visible" color=color fill="none" stroke="currentColor" stroke-width=weight stroke-linecap="round" stroke-linejoin="round"`,
    `          path d=(on ? "${polyline(target, item.closed)}" : "${polyline(item.a, item.closed)}") transition=(still ? "none" : "d ${SPRING}")`,
  ].join('\n');
}

async function morph([component, from, to]) {
  const plan = buildPlan(resampleIcon(await lucide(from)), resampleIcon(await lucide(to)));
  if (plan.items.some(item => item.block)) throw new Error(`${from} → ${to}: morphicons transports a block; Contract draws each pair alone`);
  return `// ${from} → ${to} (lucide ${version('lucide')}), ${plan.items.length} subpaths matched by morphicons' plan.
component ${component}
  props
    on: bool
    size: number
    color: string
    weight: number
    still: bool
  view
    box width=\`\${size / 16}rem\` height=\`\${size / 16}rem\` position="relative" flex-shrink=0 aria-hidden=true
${plan.items.map(pair).join('\n')}
`;
}

export async function generate() {
  const morphs = [];
  for (const entry of MORPHS) morphs.push(await morph(entry));
  const text = `// Generated by examples/t3-code/tools/generate/gen-morph.mjs; do not edit.
// MorphIcon (MIT reference, see LICENSE-T3: apps/web/src/components/MorphIcon.tsx
// over morphicons ${version('morphicons')}, upstream f2cc80a7a4): an icon that morphs to its next
// lucide shape on the "snappy" spring (stiffness 420, damping 30, mass 1;
// slight overshoot, settled in ~0.35 s), interruptibly, and swaps instantly
// under Reduce Motion. morphicons resamples both icons to 64 points per
// subpath, pairs the subpaths, and moves each pair in polar form: its centroid
// drifts, it turns by θ about its pivot and its shape moves to the target's.
// Since exact2 #188 a path's \`d\` transitions (same commands at both ends), so
// each pair below is drawn that way: a box that drifts and turns on the spring,
// holding a path whose \`d\` moves from the source polyline to the target's
// unturned one. The data is morphicons' own plan for each pair (the ends match
// its t=1 output to 0.01 units). Only the scale differs mid-flight (linear in
// \`d\` where morphicons scales by σ^t). A chevron flipping direction is the
// same glyph turned (θ = 90° or 180°, σ = 1), so it turns on the spring.
use ShellIcon from "./shell-icons.contract"

// ChevronDown ↔ ChevronUp (or Right ↔ Down with \`quarter\`): one chevron turned on the spring.
component MorphChevron
  props
    open: bool
    quarter: bool
    size: number
    color: string
    still: bool
  view
    box display="flex" flex-shrink=0 rotate=(open ? (quarter ? "90deg" : "180deg") : "0deg") transition=(still ? "none" : "rotate ${SPRING}") aria-hidden=true
      ShellIcon(name=(quarter ? "chevron-right" : "chevron-down"), size=size, color=color)

${morphs.join('\n')}`;
  return [{ file: join(example, 'src', 'shell', 'shell-morph.contract'), text }];
}
