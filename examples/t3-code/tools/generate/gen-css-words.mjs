// css-words.ts: the word lists of the CSS grammar the reference highlights with (Shiki 4.2,
// @shikijs/langs css, MIT, pinned in package.json; see LICENSE-T3), as two anchored, case-blind
// alternations for html-syntax.ts. generate.mjs writes the file.

import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const example = join(here, '..', '..');
const version = (name) => JSON.parse(readFileSync(join(here, 'node_modules', name, 'package.json'), 'utf8')).version;

/** A word-list rule's alternation, its word-boundary guards and case flag taken off. */
function words(rule) {
  const match = /^(?:\(\?i\))?\(\?<!\[-\\w\]\)(.*)\(\?!\[-\\w\]\)$/.exec(rule.match);
  if (!match) throw new Error(`${rule.name}: not a guarded word list: ${rule.match.slice(0, 80)}`);
  // `(?i:…)` keeps its group; the whole alternation is case-blind anyway.
  return match[1].replace(/^\(\?i:/, '(?:');
}
const chunked = (pattern) => {
  const lines = [];
  for (let at = 0; at < pattern.length; at += 150) lines.push(`  + ${JSON.stringify(pattern.slice(at, at + 150))}`);
  return lines.join('\n');
};

export async function generate() {
  const css = (await import(join(here, 'node_modules/@shikijs/langs/dist/css.mjs'))).default.find(grammar => grammar.name === 'css');
  const rule = (key, name) => {
    const found = css.repository[key].patterns.find(pattern => pattern.name === name);
    if (!found) throw new Error(`the css grammar's ${key} has no ${name}`);
    return words(found);
  };
  const property = rule('property-names', 'support.type.property-name.css');
  const value = [
    rule('property-keywords', 'support.constant.property-value.css'),
    rule('property-keywords', 'support.constant.property-value.list-style-type.css'),
    rule('color-keywords', 'support.constant.color.w3c-extended-color-name.css'),
    rule('color-keywords', 'support.constant.color.w3c-standard-color-name.css'),
    rule('property-keywords', 'support.constant.font-name.css'),
  ].join('|');
  const text = `// Generated by examples/t3-code/tools/generate/gen-css-words.mjs; do not edit. The word
// lists of the CSS grammar the reference highlights with (Shiki 4.2, @shikijs/langs@${version('@shikijs/langs')} css.mjs, MIT;
// see LICENSE-T3): support.type.property-name and the support.constant property-value,
// list-style-type, colour and font-name scopes, which the pierre themes colour. The patterns are
// the grammar's own alternations.

export const CSS_PROPERTY = new RegExp('^(?:'
${chunked(property)}
  + ')$', 'i');

export const CSS_VALUE = new RegExp('^(?:'
${chunked(value)}
  + ')$', 'i');
`;
  // The iOS app's bake captures only mobile/, so its html syntax reads its own copy of the same words.
  return [{ file: join(example, 'mobile', 'shared', 'r7-polish-css-words.ts'), text }];
}
