export const can = (host: { ready: boolean; scopes: readonly string[] }, permission: Permission): boolean => host.ready && host.scopes?.includes(permission) === true;
export function requirePermission(scopes: readonly string[], permission: Permission): void {
  if (!scopes?.includes(permission)) throw new ClientError(`This connection requires ${permission}.`);
}
export function settingsPatchPermissions(patch: Obj): Permission[] {
  let providers = false, settings = false;
  for (const [key, value] of Object.entries(patch)) {
    if (value === undefined) continue;
    if (['providers', 'providerInstances', 'usageLimitSources'].includes(key)) providers = true;
    else settings = true;
  }
  return [...(settings || !providers ? ['settings:write' as const] : []), ...(providers ? ['providers:manage' as const] : [])];
}
export function rpcPermissions(method: string, payload: Obj): Permission[] {
  if (method === 'server.retryResourceTelemetry') return ['environment:maintain', 'diagnostics:read'];
  if (method === 'assets.createUrl') return [['workspace-file', 'media-file', 'draft-workspace-file'].includes(str(obj(payload.resource)._tag)) ? 'filesystem:read' : 'orchestration:read'];
  if (method === 'server.updateSettings') {
    const patch = obj(payload.patch), permissions = settingsPatchPermissions(patch);
    if (payload.providerInstanceMutation === undefined) return permissions;
    return Object.values(patch).every(value => value === undefined) ? ['providers:manage'] : [...new Set<Permission>([...permissions, 'providers:manage'])];
  }
  if (method === 'projects.mutate') return payload.type === 'project.delete' || payload.scripts === undefined ? ['orchestration:operate'] : ['orchestration:operate', 'settings:write'];
  if (method === 'git.preparePullRequestThread' && payload.mode === 'worktree' && payload.threadId !== undefined) return ['source-control:write', 'orchestration:operate'];
  // A pull request generated for a thread includes that thread's context.
  if (method === 'git.runStackedAction' && payload.threadId !== undefined && (payload.action === 'create_pr' || payload.action === 'commit_push_pr')) return ['source-control:write', 'orchestration:read'];
  if (method === 'device.list' && (payload.retryHostId !== undefined || payload.updateTool === true)) return ['orchestration:operate'];
  const permission = RPC_SCOPES[method];
  return permission ? [permission] : [];
}
export function requireRpcPermissions(scopes: readonly string[], request: unknown): void {
  const value = obj(request), method = str(value.method);
  if (value.op !== 'request' && value.op !== 'subscribe') return;
  for (const permission of rpcPermissions(method, obj(value.payload))) requirePermission(scopes, permission);
}
