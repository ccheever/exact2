fn check(cases: &[(&str, [Frames; 2])]) {
    let mut failures = Vec::new();
    for (item, frames) in cases {
        for (tag, kind, index) in [
            ("canvas", NodeType::Canvas, 0),
            ("img", NodeType::Image, 0),
            ("iframe", NodeType::WebView, 1),
            ("video", NodeType::Video, 1),
            ("svg", NodeType::Svg, 1),
        ] {
            let k = lay_out_held("row", item, kind, false);
            let want: Vec<_> = (2..).zip(frames[index].iter().copied()).collect();
            failures.extend(mismatches(&format!("{tag} {item}"), &k, &want));
        }
    }
    assert!(
        failures.is_empty(),
        "{}\n{} failures",
        failures.join("\n"),
        failures.len()
    );
}
