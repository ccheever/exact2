//! The Rust binding of a module's names that take positional parameters
//! (LLP 1133.006 D8 item 1, D7: `exact_data::modules::clipboard::{write,
//! write_text, ClipboardItem}`). Such a name has no Contract form, so no row
//! in the plan, and [`crate::module_rust`] never sees it: this reads the
//! interface's `exact.json` itself. Per name a request builder and a reply
//! parser, and per record keyed by string a struct, its values an enum of
//! the kinds its `of` names (`string`, `bytes`, `path`).
//!
//! The wire is TypeScript's binding's: bytes as `{"$bytes": base64}`, a
//! path as `{"$path": …}`, a sequence's place as `$sequence`. Rust awaits
//! nothing before it sends, so its order is the order the requests are made.

use crate::rust::field_name;
use serde_json::Value as Json;
use std::fmt::Write;

/// The binding of the positional names of the interface whose `exact.json`
/// is `declaration`, as `pub mod <extension>`; an empty string when it has
/// none.
pub fn module_rust_declared(declaration: &str) -> Result<String, String> {
    let json: Json =
        serde_json::from_str(declaration).map_err(|e| format!("exact.json is not JSON: {e}"))?;
    let package = json["name"].as_str().ok_or("an interface has a `name`")?;
    let extension = package.rsplit('/').next().unwrap_or(package);
    let names: Vec<&Json> = (json["names"].as_array().into_iter().flatten())
        .filter(|n| n["params"].is_object())
        .collect();
    if names.is_empty() {
        return Ok(String::new());
    }
    let mut out = format!(
        "// @generated by `contract::module_rust_declared` from {package}'s exact.json; do not edit.\n\n\
         /// `{extension}`'s names that take positional parameters (LLP 1133.006 D8).\n\
         pub mod {} {{\n    #![allow(clippy::all, dead_code)]\n    use exact_data::modules as m;\n",
        field_name(extension)
    );
    let shapes = json["shapes"].as_object().cloned().unwrap_or_default();
    for (shape, fields) in &shapes {
        if fields["record"] == "string" {
            record(shape, fields, &mut out)?;
        }
    }
    let mut sequences = Vec::new();
    for entry in names {
        if let Some(seq) = entry["sequence"].as_str() {
            if !sequences.contains(&seq) {
                sequences.push(seq);
                writeln!(
                    out,
                    "\n    static SEQUENCE_{}: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);",
                    seq.to_ascii_uppercase()
                )
                .unwrap();
            }
        }
        call(extension, entry, &shapes, &mut out)?;
    }
    out.push_str("}\n");
    Ok(out)
}

/// The kinds a value may be, in a fixed order: each an enum variant.
fn kinds(of: &str) -> Vec<&'static str> {
    let named: Vec<&str> = of.split('|').map(str::trim).collect();
    ["string", "bytes", "path"]
        .into_iter()
        .filter(|k| named.contains(k))
        .collect()
}

fn record(shape: &str, fields: &Json, out: &mut String) -> Result<(), String> {
    let of = fields["of"]
        .as_str()
        .ok_or_else(|| format!("`{shape}` names what it is `of`"))?;
    let value = format!("{shape}Value");
    let keys: Vec<&str> = (fields["keys"].as_object().into_iter().flatten())
        .map(|(k, _)| k.as_str())
        .collect();
    writeln!(out, "\n    /// One value of a `{shape}`.\n    #[derive(Debug, Clone, PartialEq)]\n    pub enum {value} {{").unwrap();
    for kind in kinds(of) {
        let (variant, ty, doc) = variant(kind);
        writeln!(out, "        /// {doc}\n        {variant}({ty}),").unwrap();
    }
    out.push_str("    }\n");
    writeln!(
        out,
        "\n    /// `{shape}`: a record of type to data, in order.\n    \
         #[derive(Debug, Clone, PartialEq, Default)]\n    \
         pub struct {shape}(pub Vec<(String, {value})>);\n\n    \
         impl {shape} {{\n        \
         pub fn new<K: Into<String>>(items: impl IntoIterator<Item = (K, {value})>) -> Self {{\n            \
         Self(items.into_iter().map(|(k, v)| (k.into(), v)).collect())\n        }}\n        \
         /// Its types, in order.\n        \
         pub fn types(&self) -> Vec<&str> {{\n            self.0.iter().map(|(k, _)| k.as_str()).collect()\n        }}\n        \
         /// Whether the module writes `kind` (its declared `keys`).\n        \
         pub fn supports(kind: &str) -> bool {{\n            {keys:?}.contains(&kind)\n        }}\n        \
         fn wire(&self, name: &str) -> Result<m::serde_json::Value, m::ModuleError> {{\n            \
         let mut o = m::serde_json::Map::new();\n            \
         for (k, v) in &self.0 {{\n                \
         let json = match v {{"
    )
    .unwrap();
    for kind in kinds(of) {
        let (variant, _, _) = variant(kind);
        let encode = match kind {
            "string" => "m::serde_json::Value::String(x.clone())",
            "bytes" => "m::bytes(name, x)?",
            _ => "m::path(x)",
        };
        writeln!(
            out,
            "                    {value}::{variant}(x) => {encode},"
        )
        .unwrap();
    }
    out.push_str(
        "                };\n                o.insert(k.clone(), json);\n            }\n            \
         Ok(m::serde_json::Value::Object(o))\n        }\n    }\n",
    );
    Ok(())
}

fn variant(kind: &str) -> (&'static str, &'static str, &'static str) {
    match kind {
        "string" => ("Text", "String", "A string."),
        "bytes" => ("Bytes", "Vec<u8>", "Bytes, at most `m::MAX_CALL_BYTES`."),
        _ => (
            "Path",
            "String",
            "An `app:/` path the source's `fs.read` covers.",
        ),
    }
}

/// A parameter's Rust type and how its value is encoded.
fn param(
    name: &str,
    ty: &str,
    shapes: &serde_json::Map<String, Json>,
) -> Result<(String, String), String> {
    let ty = ty.trim();
    let v = field_name(name);
    if let Some(inner) = ty.strip_suffix("[]") {
        if shapes.get(inner).is_some_and(|s| s["record"] == "string") {
            return Ok((
                format!("&[{inner}]"),
                format!("m::serde_json::Value::Array({v}.iter().map(|x| x.wire(AT)).collect::<Result<_, _>>()?)"),
            ));
        }
    }
    if shapes.get(ty).is_some_and(|s| s["record"] == "string") {
        return Ok((format!("&{ty}"), format!("{v}.wire(AT)?")));
    }
    Ok(match ty {
        "string" | "strings-key" => (
            "&str".into(),
            format!("m::serde_json::Value::String({v}.to_owned())"),
        ),
        "number" => ("f64".into(), format!("m::serde_json::json!({v})")),
        "bool" => ("bool".into(), format!("m::serde_json::Value::Bool({v})")),
        "bytes" => ("&[u8]".into(), format!("m::bytes(AT, {v})?")),
        "path" => ("&str".into(), format!("m::path({v})")),
        other => return Err(format!("`{name}`'s type `{other}` has no Rust form yet")),
    })
}

fn call(
    extension: &str,
    entry: &Json,
    shapes: &serde_json::Map<String, Json>,
    out: &mut String,
) -> Result<(), String> {
    let (verb, name) = match (entry["send"].as_str(), entry["source"].as_str()) {
        (Some(n), _) => ("send", n),
        (None, Some(n)) => ("source", n),
        _ => return Err("each of `names` is a `source` or a `send`".into()),
    };
    if !entry["answers"].is_null() {
        return Err(format!(
            "`{name}` answers something: a positional name's Rust binding takes a send that answers nothing"
        ));
    }
    let f = field_name(name);
    let mut params = Vec::new();
    let mut puts = String::new();
    for (p, ty) in entry["params"].as_object().into_iter().flatten() {
        let ty = ty
            .as_str()
            .ok_or_else(|| format!("`{name}`'s `{p}` is a type"))?;
        let (rust, encode) = param(p, ty, shapes)?;
        params.push(format!("{}: {rust}", field_name(p)));
        writeln!(puts, "        args.insert({p:?}.into(), {encode});").unwrap();
    }
    let sequence = match entry["sequence"].as_str() {
        Some(s) => format!(
            "        m::sequence(&mut args, &SEQUENCE_{});\n",
            s.to_ascii_uppercase()
        ),
        None => String::new(),
    };
    writeln!(
        out,
        "\n    /// `{name}`: its request. `DataError` for bytes past what a call carries.\n    \
         pub fn {f}({}) -> Result<exact_runner::Request, m::ModuleError> {{\n        \
         const AT: &str = \"{extension}.{name}\";\n        \
         let mut args = m::serde_json::Map::new();\n{puts}        \
         let mut args = m::serde_json::Value::Object(args);\n{sequence}        \
         Ok(m::request({extension:?}, {verb:?}, {name:?}, args))\n    }}\n    \
         /// The reply to [`{f}`]'s request: done, or the module's error.\n    \
         pub fn {f}_reply(outcome: &exact_runner::Outcome) -> Result<(), m::ModuleError> {{\n        \
         m::reply(\"{extension}.{name}\", outcome).map(|_| ())\n    }}",
        params.join(", ")
    )
    .unwrap();
    Ok(())
}
