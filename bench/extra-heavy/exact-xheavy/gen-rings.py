#!/usr/bin/env python3
"""gen-rings.py -> rings.contract: the live row's progress ring (SPEC 15) and one `@keyframes`
per base value. A ring's arc is p = clamp(base + 0.2 sin(2π(t/4 + i/3)), 0, 1): a 4 s loop around
the row's own base. CSS would write one keyframes rule over `var(--base)`; Contract keyframes
take literal values only (no custom properties), so each base (two decimals: 0.00 … 1.00) gets its
own rule, 16 linear segments of the sine — the way generated CSS utilities are written."""
import math, os
HERE = os.path.dirname(os.path.abspath(__file__))
out = ['// Generated by gen-rings.py. Do not edit; re-run the script.', '']
for b in range(101):
    out.append(f'keyframes ring{b}')
    for k in range(17):
        x = k / 16
        p = min(1.0, max(0.0, b / 100 + 0.2 * math.sin(2 * math.pi * x)))
        at = 'from' if k == 0 else 'to' if k == 16 else f'{round(x * 100, 2)}%'
        out.append(f'  {at} stroke-dashoffset={round(1 - p, 4)}')
    out.append('')
out += [
    '// One ring: 56 pt, the stroke centred on radius 25, 6 wide with round caps over a #E5E5EA',
    '// track, the arc from 12 o\'clock clockwise (`pathLength=1`: the dash offset is 1 − p).',
    '// Frozen, p is the base. The label is the base, static.',
    'component Ring',
    '  props',
    '    v: number',
    '    color: string',
    '    phase: number',
    '    frozen: bool',
    '  view',
    '    box width=56 height=56 flex-shrink=0 position="relative"',
    '      svg viewBox="0 0 56 56" width=56 height=56 display="block"',
    '        circle cx=28 cy=28 r=25 fill="none" stroke="#E5E5EA" stroke-width=6',
    '        circle cx=28 cy=28 r=25 fill="none" stroke=color stroke-width=6 stroke-linecap="round" pathLength=1 stroke-dasharray="1 1" stroke-dashoffset=(1 - v) transform="rotate(-90 28 28)" animation=(frozen ? "none" : `ring${floor(v * 100 + 0.5)} 4000ms linear ${0 - phase * 4000 / 3}ms infinite`)',
    '      box position="absolute" top=0 left=0 width=56 height=56 display="flex" align-items="center" justify-content="center"',
    '        text `${floor(v * 100 + 0.5)}%` font-size=12 font-weight=600 color="#000000"',
    '',
]
open(os.path.join(HERE, 'rings.contract'), 'w').write('\n'.join(out))
print('rings.contract')
