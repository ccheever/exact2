#!/usr/bin/env python3
"""gen-svgs.py — ../data/svgs.json -> svgs.contract: one component per SVG file, the way SVGR
turns each .svg into a React component. Mechanical: every element and attribute is copied as
written; gradient ids get the file's name as a prefix (as SVGR does) so two inline SVGs on one
screen cannot collide. ../prepare.sh runs it; the output is not committed."""
import json, os, re, xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
svgs = json.load(open(os.path.join(HERE, '..', 'data', 'svgs.json')))
NUM = re.compile(r'^-?\d+(\.\d+)?$')


def camel(name):
    return ''.join(p.capitalize() for p in re.split(r'[-_]', name))


def val(v, prefix):
    v = v.replace('url(#', f'url(#{prefix}-')
    if NUM.match(v):
        return v
    return json.dumps(v)


def emit(el, prefix, depth, out, root=False):
    tag = el.tag.split('}')[-1]
    attrs = []
    for k, v in el.attrib.items():
        k = k.split('}')[-1]
        if root and k in ('width', 'height', 'xmlns'):
            continue  # the use site sizes the svg (CSS width/height)
        if k == 'id':
            v = f'{prefix}-{v}'
        attrs.append(f'{k}={val(v, prefix)}')
    out.append('  ' * depth + ' '.join([tag] + attrs))
    for c in el:
        emit(c, prefix, depth + 1, out)


lines = ['// Generated by gen-svgs.py from ../data/svgs.json — one component per SVG file (SVGR style).',
         '// Do not edit; re-run the script.', '']
names = sorted(svgs)
for name in names:
    root = ET.fromstring(svgs[name])
    lines.append(f'component Svg{camel(name)}')
    lines.append('  view')
    body = []
    emit(root, name, 2, body, root=True)
    body[0] = body[0] + ' width="100%" height="100%" display="block"'
    lines.extend(body)
    lines.append('')
# The index: one component per family that shows the file a row names (an SVGR index).
for fam, prefix, what in (('Icon', 'icon-', 'an icon'), ('Chart', 'chart-', 'a chart'), ('Art', 'art-', 'an illustration')):
    lines.append(f'// {what} by its file name ({prefix}…); the box that holds it sizes it.')
    lines.append(f'component {fam}')
    lines.append('  props')
    lines.append('    name: string')
    lines.append('  view')
    lines.append('    box width="100%" height="100%"')
    for name in names:
        if name.startswith(prefix):
            key = name[len(prefix):]
            lines.append(f'      when name == "{key if fam == "Icon" else name}"')
            lines.append(f'        Svg{camel(name)}()')
    lines.append('')
open(os.path.join(HERE, 'svgs.contract'), 'w').write('\n'.join(lines))
print(len(names), 'components')
