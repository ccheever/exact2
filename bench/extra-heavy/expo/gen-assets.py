#!/usr/bin/env python3
"""Writes assets.ts (static require() maps Metro can bundle), embed.ts (the web view template as a
string) and assets/icon.png (data/images/avatar-00.jpg scaled up) from ./data, the copy of ../data
that ../prepare.sh makes here."""
import json, os
from PIL import Image
D = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'data')
out = ['// Generated by gen-assets.py from ./data — static requires for Metro.', '/* eslint-disable */']
for name, sub, exts in (('IMAGES', 'images', ('.jpg',)), ('ANIM', 'anim', ('.gif', '.webp')),
                        ('LOTTIE', 'anim', ('.json',)), ('VIDEO', 'video', ('.mp4',))):
    out.append(f'export const {name}: Record<string, any> = {{')
    for f in sorted(os.listdir(os.path.join(D, sub))):
        if f.endswith(exts):
            out.append(f"  '{f}': require('./data/{sub}/{f}'),")
    out.append('};')
open(os.path.join(os.path.dirname(D), 'assets.ts'), 'w').write('\n'.join(out) + '\n')
html = open(os.path.join(D, 'embed.html')).read()
open(os.path.join(os.path.dirname(D), 'embed.ts'), 'w').write(
    '// Generated by gen-assets.py: data/embed.html as a string.\nexport const EMBED_HTML = ' + json.dumps(html) + ';\n')
os.makedirs(os.path.join(os.path.dirname(D), 'assets'), exist_ok=True)
Image.open(os.path.join(D, 'images', 'avatar-00.jpg')).convert('RGB').resize((1024, 1024), Image.BICUBIC) \
    .save(os.path.join(os.path.dirname(D), 'assets', 'icon.png'))
