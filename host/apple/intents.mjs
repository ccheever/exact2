// @ref LLP 1133.023 D8, D9, D10 — the generated intents module: one Swift
// file per app from its faces, compiled to an object the executable links,
// and the App Intents metadata the system reads from the bundle.
//
// The generated code imports only AppIntents and Foundation. It reaches the
// host through `NotificationCenter`, the channel ExactKit and an app's
// modules already share in the process (ExactTools.swift): `exact.tools.call`
// for a call, `exact.contentIndex.query` for an entity query and
// `exact.contentIndex.open` for an entity's location. So it compiles beside
// the SwiftPM build, not inside it, and needs no ExactKit module to compile
// against.
import { resolve } from 'node:path';
import { existsSync, mkdirSync, rmSync, writeFileSync, cpSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';

const toolchain = '/Applications/Xcode.app/Contents/Developer/Toolchains/XcodeDefault.xctoolchain';
/** The protocols whose conformers' constant values the metadata pass reads (Xcode's list for App Intents). */
const gathered = ['AppIntent', 'EntityQuery', 'AppEntity', 'TransientEntity', 'AppEnum', 'AppShortcutProviding', 'AppShortcutsProvider',
  'AnyResolverProviding', 'AppIntentsPackage', 'DynamicOptionsProvider', 'OpenIntent', 'EntityStringQuery'];

/** The faces this platform compiles: `compat.inputs.faces` of the bake, each `{signature, face}` whose doors name `apple`. */
export const appleFaces = (compat) => (compat?.inputs?.faces ?? []).filter(f => (f.face?.doors ?? []).includes('apple'));

const typeName = (name) => name[0].toUpperCase() + name.slice(1);
const literal = (text) => JSON.stringify(String(text)).replace(/\\u([0-9a-f]{4})/g, (_, h) => `\\u{${h}}`);
const entityType = (kind) => `${typeName(kind)}Entity`;

/** A parameter's Swift type from its plan type and its face, or a reason it has none. */
function swiftType(planType, face) {
  const optional = /^option<(.*)>$/.exec(planType);
  const inner = optional ? optional[1] : planType;
  let type;
  if (face?.entity) type = inner === 'string' ? entityType(face.entity) : null;
  else if (inner === 'string') type = 'String';
  else if (inner === 'bool') type = 'Bool';
  else if (inner === 'number') type = face?.type === 'integer' ? 'Int' : 'Double';
  else type = null;
  if (!type) throw new Error(`host/apple: intents: a parameter of type ${planType} has no App Intents type (the compiler's intents-face-type should have refused it)`);
  return { type, optional: !!optional, entity: !!face?.entity };
}

/** A phrase's `${applicationName}` and `${<parameter>}` as App Shortcuts' interpolations. */
function phrase(text, parameters) {
  const parts = String(text).split(/(\$\{[A-Za-z_][A-Za-z0-9_]*\})/);
  return '"' + parts.map(part => {
    const name = /^\$\{(.*)\}$/.exec(part)?.[1];
    if (!name) return literal(part).slice(1, -1);
    if (name === 'applicationName') return '\\(.applicationName)';
    if (!parameters.includes(name)) throw new Error(`host/apple: intents: a phrase names \${${name}}, which is not a parameter`);
    return `\\(\\.$${name})`;
  }).join('') + '"';
}

const authentication = (word) => ({ local: '.requiresLocalDeviceAuthentication', always: '.alwaysAllowed' })[word] ?? '.requiresAuthentication';

/** The Swift of the app's intents module. */
export function intentsSource(faces, entities = {}) {
  const kinds = [...new Set(faces.flatMap(f => Object.values(f.face.parameters ?? {}).map(p => p.entity).filter(Boolean)))].sort();
  const out = [`// Generated by host/apple/intents.mjs from app.json's \`intents\` and the plan's tools (LLP 1133.023 D8). Not edited by hand.
import AppIntents
import Foundation

/// The host's door and mirror, through the channel ExactKit observes (ExactTools.swift).
enum ExactDoor {
    struct Refusal: Error, CustomLocalizedStringResourceConvertible {
        let message: String
        var localizedStringResource: LocalizedStringResource { "\\(message)" }
    }

    /// Hands the host a call and awaits its answer (LLP 1111 D4's envelope).
    @MainActor static func call(_ tool: String, _ args: [String: Any], digest: String) async throws -> [String: Any] {
        let answer: [String: Any] = await withCheckedContinuation { done in
            let body = NSMutableDictionary(dictionary: ["tool": tool, "args": args, "door": "apple", "digest": digest])
            body["reply"] = { (answer: [String: Any]) in done.resume(returning: answer) }
            NotificationCenter.default.post(name: Notification.Name("exact.tools.call"), object: body)
            if body["taken"] as? Bool != true { done.resume(returning: ["outcome": "refused", "message": "This app has no tool door."]) }
        }
        guard answer["outcome"] as? String == "ok" else {
            let message = answer["message"] as? String ?? ""
            throw Refusal(message: message.isEmpty ? "\\(tool): \\(answer["outcome"] as? String ?? "failed")" : message)
        }
        return answer
    }

    /// The mirror's entries of \`kind\`: by id, matching a string, or all in the app's order.
    static func entries(_ kind: String, ids: [String]? = nil, matching: String? = nil) -> [[String: Any]] {
        let body = NSMutableDictionary(dictionary: ["kind": kind])
        if let ids { body["ids"] = ids }
        if let matching { body["matching"] = matching }
        NotificationCenter.default.post(name: Notification.Name("exact.contentIndex.query"), object: body)
        return body["entries"] as? [[String: Any]] ?? []
    }

    /// Opens an entry's location, as a search result's continuation does.
    @MainActor static func open(_ url: String) {
        NotificationCenter.default.post(name: Notification.Name("exact.contentIndex.open"), object: NSMutableDictionary(dictionary: ["url": url]))
    }
}
`];
  for (const kind of kinds) {
    const T = entityType(kind), title = entities[kind]?.title ?? typeName(kind);
    out.push(`
struct ${T}: AppEntity {
    static let typeDisplayRepresentation: TypeDisplayRepresentation = ${literal(title)}
    static let defaultQuery = ${T}Query()
    let id: String
    let title: String
    let subtitle: String?
    let url: String
    var displayRepresentation: DisplayRepresentation {
        DisplayRepresentation(title: "\\(title)", subtitle: subtitle.map { "\\($0)" })
    }
    init?(_ entry: [String: Any]) {
        guard let id = entry["id"] as? String, let title = entry["title"] as? String else { return nil }
        self.id = id; self.title = title
        subtitle = entry["description"] as? String
        url = entry["url"] as? String ?? "/"
    }
}

struct ${T}Query: EntityStringQuery {
    func entities(for identifiers: [${T}.ID]) async throws -> [${T}] {
        ExactDoor.entries(${literal(kind)}, ids: identifiers).compactMap(${T}.init)
    }
    func entities(matching string: String) async throws -> [${T}] {
        ExactDoor.entries(${literal(kind)}, matching: string).compactMap(${T}.init)
    }
    func suggestedEntities() async throws -> [${T}] {
        ExactDoor.entries(${literal(kind)}).compactMap(${T}.init)
    }
}

struct Open${T}: OpenIntent {
    static let title: LocalizedStringResource = ${literal(`Open ${title}`)}
    @Parameter(title: ${literal(title)}) var target: ${T}
    @MainActor func perform() async throws -> some IntentResult {
        ExactDoor.open(target.url)
        return .result()
    }
}
`);
  }
  for (const { signature, face } of faces) {
    const T = typeName(signature.name);
    const params = signature.parameters.map(([name, planType]) => ({ name, ...swiftType(planType, face.parameters?.[name]), title: face.parameters?.[name]?.title ?? name }));
    const fields = params.map(p => `    @Parameter(title: ${literal(p.title)}) var ${p.name}: ${p.type}${p.optional ? '?' : ''}`).join('\n');
    const value = (p) => p.entity ? `${p.name}${p.optional ? '?' : ''}.id` : p.name;
    const args = params.length ? `[${params.map(p => `${literal(p.name)}: ${p.optional ? `${value(p)} as Any? ?? NSNull()` : value(p)}`).join(', ')}]` : '[:]';
    out.push(`
struct ${T}: AppIntent {
    static let title: LocalizedStringResource = ${literal(face.title ?? signature.name)}
    static let description = IntentDescription(${literal(signature.description)})
    static let authenticationPolicy: IntentAuthenticationPolicy = ${authentication(face.apple?.authentication)}
${fields}
    @MainActor func perform() async throws -> some IntentResult {
${signature.consequence === 'destroys' ? '        try await requestConfirmation()\n' : ''}        _ = try await ExactDoor.call(${literal(signature.name)}, ${args}, digest: ${literal(face.digest ?? '')})
        return .result()
    }
}
`);
  }
  const phrased = faces.filter(f => f.face.apple?.phrases?.length);
  if (phrased.length) {
    out.push(`
struct ExactAppShortcuts: AppShortcutsProvider {
    static var appShortcuts: [AppShortcut] {
${phrased.map(({ signature, face }) => `        AppShortcut(intent: ${typeName(signature.name)}(), phrases: [${face.apple.phrases.map(p => phrase(p, signature.parameters.map(([n]) => n))).join(', ')}], shortTitle: ${literal(face.title ?? signature.name)}, systemImageName: ${literal(face.apple.systemImage ?? 'app')})`).join('\n')}
    }
}
`);
  }
  // What ExactKit calls by name, since it cannot name the generated types: an Objective-C class is kept by the link.
  out.push(`
@objc(ExactIntentsHooks) final class ExactIntentsHooks: NSObject {
    /// The index changed: App Shortcuts whose phrases name a parameter learn its values (D9).
    @objc static func parametersChanged() {
        ${phrased.length ? 'ExactAppShortcuts.updateAppShortcutParameters()' : '// no App Shortcuts'}
    }
}
`);
  return out.join('');
}

/** The manifest's `shortcuts` as the bundle declares them (D3): iOS's Home Screen quick actions, each carrying its
 * location, and the Mac's Dock menu, which ExactShortcuts reads; none on tvOS, which has neither. */
export function shortcutKeys(app, platform) {
  const items = app.manifest.shortcuts ?? [];
  if (!items.length || platform === 'tvos') return {};
  if (platform === 'macos') return { ExactShortcutItems: items.map(({ name, url }) => ({ name, url })) };
  return { UIApplicationShortcutItems: items.map(item => ({ UIApplicationShortcutItemType: item.url, UIApplicationShortcutItemTitle: item.name,
    ...(item.description ? { UIApplicationShortcutItemSubtitle: item.description } : {}),
    ...(item.apple?.symbol ? { UIApplicationShortcutItemIconSymbolName: item.apple.symbol } : {}),
    UIApplicationShortcutItemUserInfo: { url: item.url } })) };
}

/** The floor of what the generated code uses: App Shortcuts' short titles and symbols are iOS 17 and macOS 14 (D17). */
const floor = { ios: 17, macos: 14 };

/**
 * Compile the app's intents module for `triple` and extract its metadata. Answers `{ object, digest, place(bundleResources) }`,
 * or null with no face for Apple. Kept by the digest of its source and compiler, so an unchanged face set compiles once.
 */
export function buildIntents({ app, compat, directory, sdkName, sdk, triple, platform, deployment, swiftc, runApple }) {
  const faces = appleFaces(compat);
  if (!faces.length) return null;
  if (parseFloat(deployment) < floor[platform]) throw new Error(`host/apple: intents: a faced tool needs ${platform === 'ios' ? 'iOS' : 'macOS'} ${floor[platform]} or later, and app.json's host.${platform}.minimumOS is ${deployment}`);
  const source = intentsSource(faces, app.manifest.intents?.entities ?? {});
  const digest = createHash('sha256').update(JSON.stringify([source, swiftc, triple, sdk])).digest('hex').slice(0, 16);
  const dir = resolve(directory, digest), object = resolve(dir, 'ExactIntents.o'), metadata = resolve(dir, 'Metadata.appintents');
  if (!existsSync(resolve(metadata, 'extract.actionsdata'))) {
    rmSync(dir, { recursive: true, force: true });
    mkdirSync(dir, { recursive: true });
    const file = resolve(dir, 'ExactIntents.swift'), values = resolve(dir, 'ExactIntents.swiftconstvalues');
    writeFileSync(file, source);
    writeFileSync(resolve(dir, 'protocols.json'), JSON.stringify(gathered));
    const started = Date.now();
    runApple('xcrun', ['--sdk', sdkName, 'swiftc', '-parse-as-library', '-wmo', '-O', '-swift-version', '5', '-module-name', 'ExactIntents',
      '-module-cache-path', resolve(directory, 'module-cache'), '-target', triple, '-sdk', sdk,
      '-emit-const-values-path', values, '-Xfrontend', '-const-gather-protocols-file', '-Xfrontend', resolve(dir, 'protocols.json'),
      '-c', file, '-o', object]);
    writeFileSync(resolve(dir, 'sources.txt'), file + '\n');
    writeFileSync(resolve(dir, 'values.txt'), values + '\n');
    writeFileSync(resolve(dir, 'none.txt'), '');
    const xcode = /Build version (\S+)/.exec(spawnSync('xcodebuild', ['-version'], { encoding: 'utf8' }).stdout ?? '')?.[1] ?? '';
    runApple(resolve(toolchain, 'usr/bin/appintentsmetadataprocessor'), ['--toolchain-dir', toolchain, '--module-name', 'ExactIntents', '--sdk-root', sdk,
      '--xcode-version', xcode, '--platform-family', platform === 'macos' ? 'macOS' : 'iOS', '--deployment-target', deployment, '--target-triple', triple,
      '--output', dir, '--binary-file', object, '--source-file-list', resolve(dir, 'sources.txt'), '--swift-const-vals-list', resolve(dir, 'values.txt'),
      '--metadata-file-list', resolve(dir, 'none.txt'), '--static-metadata-file-list', resolve(dir, 'none.txt'),
      '--compile-time-extraction', '--deployment-aware-processing', '--no-app-shortcuts-localization'], { stdio: 'ignore' });
    if (!existsSync(resolve(metadata, 'extract.actionsdata'))) throw new Error(`host/apple: intents: the metadata pass wrote no ${metadata}/extract.actionsdata`);
    console.log(`host/apple: intents: ${faces.length} faced tool${faces.length === 1 ? '' : 's'} compiled with their metadata (${Date.now() - started} ms)`);
  }
  return {
    object, digest, tools: faces.map(f => f.signature.name),
    /** Into the bundle's resources (the bundle's root on iOS, Contents/Resources on the Mac), before it is signed. */
    place(resources) { rmSync(resolve(resources, 'Metadata.appintents'), { recursive: true, force: true }); cpSync(metadata, resolve(resources, 'Metadata.appintents'), { recursive: true }); },
  };
}
