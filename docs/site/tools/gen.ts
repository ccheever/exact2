function slugger() {
  const seen = new Map<string, number>();
  return (text: string) => {
    const base = text.toLowerCase().trim().replace(/[^\p{L}\p{N}\s_-]/gu, '').replace(/\s/g, '-');
    const n = seen.get(base) ?? 0;
    seen.set(base, n + 1);
    return n ? `${base}-${n}` : base;
  };
}

function plain(tokens: Token[] | undefined): string {
  return (tokens ?? []).map(t => ('tokens' in t && t.tokens ? plain(t.tokens) : 'text' in t ? decode(String(t.text)) : '')).join('');
}

function decode(s: string): string {
  return s.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&amp;/g, '&');
}

function routeName(path: string): string {
  if (path === '/') return 'home';
  return path.split(/[/-]/).filter(Boolean).map((w, i) => (i ? w[0].toUpperCase() + w.slice(1) : w)).join('');
}

function read(nav: NavPage): Doc {
  const tokens = marked.lexer(readFileSync(join(DOCS, nav.source), 'utf8'), { gfm: true });
  const slug = slugger();
  const anchors = new Map<string, string>();
  const intro: Token[] = [];
  const parts: Section[] = [];
  let title = '';
  for (const t of tokens) {
    if (t.type === 'heading') {
      const text = plain(t.tokens);
      const anchor = slug(text);
      if (t.depth === 1 && !title) title = text;
      if (nav.split && t.depth === 2) parts.push({ title: text, anchor, tokens: [] });
      const current = parts.at(-1);
      const path = nav.split && current ? `${nav.path}/${current.anchor}` : nav.path;
      anchors.set(anchor, path);
    }
    (parts.at(-1)?.tokens ?? intro).push(t);
  }
  return { nav, title, intro, sections: parts.filter(s => !SKIPPED_SECTIONS.has(s.anchor)), anchors };
}

