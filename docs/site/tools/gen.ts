const links: { from: string; to: string; anchor: string; ok: boolean }[] = [];

function target(href: string, from: string): string {
  if (/^[a-z]+:/i.test(href)) return href;
  const [path, anchor = ''] = href.split('#');
  const source = path ? normalize(join(dirname(from), path)) : from;
  const doc = bySource.get(source);
  if (!doc) return `${GITHUB}/${relative(REPO, resolve(DOCS, source))}${anchor ? `#${anchor}` : ''}`;
  const page = anchor ? doc.anchors.get(anchor) : doc.nav.path;
  links.push({ from, to: `${source}#${anchor}`, anchor, ok: page !== undefined });
  const at = page ?? doc.nav.path;
  return anchor && !(doc.nav.split && SKIPPED_SECTIONS.has(anchor)) && at !== `${doc.nav.path}/${anchor}` ? `${at}#${anchor}` : at;
}

function runs(tokens: Token[] | undefined, from: string, next: () => string, style = { strong: false, em: false, href: '' }): Run[] {
  const out: Run[] = [];
  const push = (text: string, code = false) => {
    if (text) out.push({ id: next(), text, code, strong: style.strong, em: style.em, href: style.href });
  };
  for (const t of tokens ?? []) {
    switch (t.type) {
      case 'strong': out.push(...runs(t.tokens, from, next, { ...style, strong: true })); break;
      case 'em': out.push(...runs(t.tokens, from, next, { ...style, em: true })); break;
      case 'del': out.push(...runs(t.tokens, from, next, style)); break;
      case 'link': out.push(...runs(t.tokens, from, next, { ...style, href: target(t.href, from) })); break;
      case 'codespan': push(decode(t.text), true); break;
      case 'br': push('\n'); break;
      case 'text': (t as Tokens.Text).tokens ? out.push(...runs((t as Tokens.Text).tokens, from, next, style)) : push(decode(t.text)); break;
      default: push(decode('text' in t ? String(t.text) : t.raw));
    }
  }
  return out;
}

function render(page: SitePage): { blocks: Block[]; toc: TocItem[] } {
  const slug = slugger();
  let n = 0;
  const next = () => `${n++}`;
  const out: Block[] = [];
  const toc: TocItem[] = [];
  const source = page.source;
  let group = '';
  let marker = '';
  let collapsibles = 0;
  let tabs: Block | null = null;
  let tabSets = 0;
  const block = (b: Partial<Block> & { kind: string }) => out.push({ id: next(), depth: 0, lang: '', text: '', href: '', group, runs: [], rows: [], lines: [], tree: [], ...b });
  const tree = (text: string): TreeRow[] => {
    const rows: TreeRow[] = [];
    const seen = new Set<string>();
    for (const line of text.split('\n').map(l => l.trim()).filter(Boolean)) {
      const parts = line.replace(/\/$/, '').split('/');
      parts.forEach((name, i) => {
        const key = parts.slice(0, i + 1).join('/');
        if (seen.has(key)) return;
        seen.add(key);
        rows.push({ id: next(), name, depth: i, folder: i < parts.length - 1 || line.endsWith('/') });
      });
    }
    return rows;
  };
  const walk = (tokens: Token[], depth: number) => {
    for (const t of tokens) {
      switch (t.type) {
        case 'heading': {
          const r = runs(t.tokens, source, next);
          const id = slug(plain(t.tokens));
          if (t.depth === 1 || id === page.skipHeading) break;
          if (t.depth === page.tocDepth) toc.push({ id: next(), title: plain(t.tokens), href: `#${id}` });
          block({ kind: 'heading', depth: t.depth, href: id, runs: r });
          break;
        }
        case 'paragraph': block({ kind: 'paragraph', depth, runs: runs(t.tokens, source, next) }); break;
        case 'code': {
          const lang = (t.lang ?? '').trim().split(/\s+/)[0];
          if (lang === 'filetree') {
            block({ kind: 'filetree', depth, text: t.text, tree: tree(t.text) });
            break;
          }
          const shiki = LANG[lang];
          const raw = shiki
            ? highlighter.codeToTokens(t.text, { lang: shiki, themes: THEMES, defaultColor: false }).tokens
            : t.text.split('\n').map(line => [{ content: line, htmlStyle: {} as Record<string, string> }]);
          const color = (style: Record<string, string> | undefined) => (style?.['--shiki-light'] && style?.['--shiki-dark'] ? `light-dark(${style['--shiki-light']}, ${style['--shiki-dark']})` : '');
          const lines = raw.map(line => ({ id: next(), tokens: line.map(tok => ({ id: next(), text: tok.content, color: color(tok.htmlStyle as Record<string, string>) })) }));
          block({ kind: TERMINAL.has(lang) ? 'terminal' : 'code', depth, lang, text: t.text, lines });
          break;
        }
        case 'hr': block({ kind: 'rule' }); break;
        case 'blockquote': {
          const inner = (t as Tokens.Blockquote).tokens ?? [];
          const first = inner[0];
          const alert = first?.type === 'paragraph' ? (first as Tokens.Paragraph).text.match(/^\[!(NOTE|TIP|IMPORTANT|WARNING|CAUTION)\]\s*/) : null;
          if (alert) {
            const head = marked.lexer((first as Tokens.Paragraph).text.slice(alert[0].length), { gfm: true });
            const paragraph = head.find(x => x.type === 'paragraph') as Tokens.Paragraph | undefined;
            block({ kind: 'callout', depth, lang: alert[1].toLowerCase(), runs: runs(paragraph?.tokens ?? [], source, next) });
            walk(inner.slice(1), depth);
            break;
          }
          block({ kind: 'quote', depth, runs: runs(inner.flatMap(p => ('tokens' in p && p.tokens) || []), source, next) });
          break;
        }
        case 'list': {
          const list = t as Tokens.List;
          const as = marker;
          marker = '';
          if (as === 'prerequisites') {
            group = `prerequisites-${collapsibles++}`;
            block({ kind: 'collapsible', lang: 'prerequisites', href: group, group: '', text: `${list.items.length} ${list.items.length === 1 ? 'requirement' : 'requirements'}` });
          }
          list.items.forEach((item, i) => {
            if (as === 'steps' || as === 'prerequisites') {
              const [first, ...rest] = item.tokens;
              const head = first && (first.type === 'text' || first.type === 'paragraph') ? runs((first as Tokens.Text).tokens ?? [first], source, next) : [];
              block({ kind: as === 'steps' ? 'step' : 'prerequisite', depth, text: `${i + 1}`, runs: head });
              walk(head.length ? rest : item.tokens, depth + 1);
              return;
            }
            const marker = list.ordered ? `${(Number(list.start) || 1) + i}.` : '•';
            const [first, ...rest] = item.tokens;
            const head = first && (first.type === 'text' || first.type === 'paragraph') ? runs((first as Tokens.Text).tokens ?? [first], source, next) : [];
            block({ kind: 'item', depth, text: marker, runs: head });
            walk(head.length ? rest : item.tokens, depth + 1);
          });
          if (as === 'prerequisites') group = '';
          break;
        }
        case 'table': {
          const table = t as Tokens.Table;
          const row = (cells: Tokens.TableCell[], header: boolean): Row => ({ id: next(), header, cells: cells.map(c => ({ id: next(), runs: runs(c.tokens, source, next) })) });
          block({ kind: 'table', rows: [row(table.header, true), ...table.rows.map(r => row(r, false))] });
          break;
        }
        case 'html': {
          const raw = t.raw.trim();
          const comment = raw.match(/^<!--\s*(steps|prerequisites)\s*-->$/);
          if (comment) { marker = comment[1]; break; }
          if (/^<!--\s*tabs\s*-->$/.test(raw)) {
            block({ kind: 'tabs', href: `tabs-${tabSets++}`, group: '' });
            tabs = out[out.length - 1];
            break;
          }
          const tab = raw.match(/^<!--\s*tab:\s*(.+?)\s*-->$/);
          if (tab && tabs) {
            group = `${tabs.href}|${tabs.text ? tabs.text.split('\n').length : 0}`;
            tabs.text = tabs.text ? `${tabs.text}\n${tab[1]}` : tab[1];
            break;
          }
          if (/^<!--\s*\/tabs\s*-->$/.test(raw)) { tabs = null; group = ''; break; }
          if (/^<!--/.test(raw)) break;
          const open = raw.match(/^<details>\s*<summary>([\s\S]*?)<\/summary>/i);
          if (open) {
            group = `details-${collapsibles++}`;
            block({ kind: 'collapsible', href: group, group: '', text: open[1].replace(/<[^>]+>/g, '').trim() });
            const after = raw.slice(open[0].length).replace(/<\/details>\s*$/i, '').trim();
            if (after) walk(marked.lexer(after, { gfm: true }), depth);
            if (/<\/details>\s*$/i.test(raw)) group = '';
            break;
          }
          if (/^<\/details>$/i.test(raw)) { group = ''; break; }
          block({ kind: 'paragraph', depth, runs: [{ id: next(), text: raw, code: false, strong: false, em: false, href: '' }] });
          break;
        }
        case 'space': break;
        default: block({ kind: 'paragraph', depth, runs: runs([t], source, next) });
      }
    }
  };
  walk(page.tokens, 0);
  return { blocks: out, toc };
}

function lead(tokens: Token[], fallback: string): string {
  const sentences = tokens
    .filter((t): t is Tokens.Paragraph => t.type === 'paragraph')
    .flatMap(p => plain(p.tokens).replace(/\s+/g, ' ').trim().split(/(?<=[.!?])\s+(?=[A-Z])/))
    .map(x => x.trim());
  const sentence = sentences.find(x => x.length >= 40 && !x.endsWith(':')) ?? fallback;
  return sentence.length > 180 ? `${sentence.slice(0, 177).trimEnd()}…` : sentence;
}

