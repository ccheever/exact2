fn date(ms: f64, offset: f64, style: &str) -> Value {
    formatting(
        Stdlib::FormatDate,
        &[Value::Number(ms), Value::Number(offset), Value::str(style)],
    )
    .expect("a date")
}

fn number(n: f64) -> Value {
    formatting(
        Stdlib::FormatNumber,
        &[Value::Number(n), Value::str("compact")],
    )
    .expect("a number")
}

#[test]
fn dates_and_times_are_intl_s_at_a_fixed_offset() {
    let mut wrong = Vec::new();
    for &(ms, offset, time, medium, month_year) in DATES {
        let got = (
            format_time(ms, offset),
            date(ms, offset, "medium"),
            date(ms, offset, "month-year"),
        );
        let want = (Value::str(time), Value::str(medium), Value::str(month_year));
        if got != want {
            wrong.push(format!("{ms} at {offset}: {got:?}, Intl {want:?}"));
        }
    }
    assert!(
        wrong.is_empty(),
        "{} of {} rows:\n{}",
        wrong.len(),
        DATES.len(),
        wrong.join("\n")
    );
}

#[test]
fn compact_numbers_are_intl_s_truncated() {
    let wrong: Vec<String> = NUMBERS
        .iter()
        .filter(|&&(n, want)| number(n) != Value::str(want))
        .map(|&(n, want)| format!("{n}: {:?}, Intl {want:?}", number(n)))
        .collect();
    assert!(
        wrong.is_empty(),
        "{} of {} rows:\n{}",
        wrong.len(),
        NUMBERS.len(),
        wrong.join("\n")
    );
}

/// D7: every entry prints `""` for a non-finite argument or an offset past
/// ±18 h, where Intl prints `NaN` or `∞`, or throws a RangeError.
#[test]
fn invalid_input_is_blank_from_every_entry() {
    for bad in [f64::NAN, f64::INFINITY, f64::NEG_INFINITY] {
        assert_eq!(number(bad), Value::str(""), "{bad}");
        for (ms, offset) in [(bad, 0.0), (0.0, bad)] {
            assert_eq!(format_time(ms, offset), Value::str(""), "{ms} at {offset}");
            assert_eq!(date(ms, offset, "medium"), Value::str(""));
            assert_eq!(date(ms, offset, "month-year"), Value::str(""));
        }
    }
    for offset in [1080.5, -1081.0, 1e9] {
        assert_eq!(format_time(0.0, offset), Value::str(""), "{offset}");
        assert_eq!(date(0.0, offset, "medium"), Value::str(""), "{offset}");
    }
    // ±18 h is the edge, as `WallTime::validate` has it.
    assert_eq!(format_time(0.0, 1080.0), Value::str("6:00 PM"));
    assert_eq!(format_time(0.0, -1080.0), Value::str("6:00 AM"));
}

/// D7's one order, where it shows: TimeClip before the shift (`-0.5` at
/// +60 is 1:00 AM, not 12:59 AM), and no zero sentinel — `0` is the epoch.
#[test]
fn the_instant_is_clipped_before_it_is_shifted() {
    assert_eq!(format_time(-0.5, 60.0), Value::str("1:00 AM"));
    assert_eq!(format_time(-0.5, 0.0), Value::str("12:00 AM"));
    assert_eq!(format_time(0.0, 0.0), Value::str("12:00 AM"));
    assert_eq!(date(-0.0, 0.0, "medium"), Value::str("Jan 1, 1970"));
    assert_eq!(format_time(-1.0, 0.0), Value::str("11:59 PM"));
    assert_eq!(format_time(3_599_999.9, 0.0), Value::str("12:59 AM"));
}

#[test]
fn a_style_outside_the_table_is_refused_not_guessed() {
    let args = [Value::Number(0.0), Value::Number(0.0), Value::str("long")];
    assert_eq!(formatting(Stdlib::FormatDate, &args), None);
    assert_eq!(
        formatting(
            Stdlib::FormatNumber,
            &[Value::Number(1.0), Value::str("integer")]
        ),
        None
    );
    // `formatTime` is the core's, never the capability's.
    assert_eq!(
        formatting(
            Stdlib::FormatTime,
            &[Value::Number(0.0), Value::Number(0.0), Value::str("short")]
        ),
        None
    );
}
