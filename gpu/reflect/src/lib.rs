/// A struct name must be a Rust identifier that is not a keyword (a raw
/// type name is not worth reading; rename it in the WGSL).
fn type_name(name: &str) -> Result<(), String> {
    if !is_identifier(name) {
        return Err(format!(
            "`{name}` cannot name a Rust struct; rename it in the WGSL"
        ));
    }
    Ok(())
}

const KEYWORDS: &[&str] = &[
    "abstract", "as", "async", "await", "become", "box", "break", "const", "continue", "crate",
    "do", "dyn", "else", "enum", "extern", "false", "final", "fn", "for", "gen", "if", "impl",
    "in", "let", "loop", "macro", "match", "mod", "move", "mut", "override", "priv", "pub", "ref",
    "return", "static", "struct", "super", "trait", "true", "try", "type", "typeof", "unsafe",
    "unsized", "use", "virtual", "where", "while", "yield",
];

fn is_identifier(s: &str) -> bool {
    let mut chars = s.chars();
    matches!(chars.next(), Some(c) if c == '_' || c.is_ascii_alphabetic())
        && chars.all(|c| c == '_' || c.is_ascii_alphanumeric())
        && !KEYWORDS.contains(&s)
        && !matches!(s, "self" | "Self" | "crate" | "super")
}

/// A field name as Rust: raw when it is a keyword.
fn ident(name: &str) -> Result<String, String> {
    if matches!(name, "self" | "Self" | "crate" | "super") || name.is_empty() {
        return Err(format!("`{name}` cannot be a Rust field"));
    }
    if KEYWORDS.contains(&name) {
        return Ok(format!("r#{name}"));
    }
    if !is_identifier(name) {
        return Err(format!("`{name}` is not a Rust identifier"));
    }
    Ok(name.to_string())
}

/// `childrenSampler` / `children_sampler` → `CHILDREN_SAMPLER`.
fn upper_snake(s: &str) -> String {
    let chars: Vec<char> = s.chars().collect();
    let mut out = String::new();
    for (i, c) in chars.iter().enumerate() {
        if c.is_ascii_uppercase()
            && i > 0
            && (chars[i - 1].is_ascii_lowercase() || chars[i - 1].is_ascii_digit())
        {
            out.push('_');
        }
        out.push(c.to_ascii_uppercase());
    }
    out
}

/// `vs_main` → `VsMain`.
fn upper_camel(s: &str) -> String {
    s.split('_')
        .filter(|p| !p.is_empty())
        .map(|p| {
            let mut c = p.chars();
            match c.next() {
                Some(f) => f.to_ascii_uppercase().to_string() + c.as_str(),
                None => String::new(),
            }
        })
        .collect()
}
